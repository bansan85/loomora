#!/usr/bin/env python
"""Measure the shared-code share per platform and variant (FR-011, SC-007, research R9, T104).

Usage:
  python tools/measure_sharing.py [--root DIR] [--format text|json] [--verbose] [--write] [--platform ID[,ID]]
                                  [--min-ratio 0.8] [--strict] [--selftest]

Counts non-empty, non-comment source lines of three kinds of code:

  backend  core/           the C++11 backend and its C API (core/src, core/include)
  glue     bridge/<name>   JNI (android) and Emscripten (web) glue; 0 for the platforms that link the
                           C API directly (Windows, Linux, macOS, iOS)
  ui       ui/<variant>/<platform>/   the native UI of one platform and variant (window, lifecycle,
                           encoding conversion, the probe line writer: everything platform-specific)

and prints, for each UI directory that has code and for each deliverable record
(docs/implementation/validation/deliverables/*.json), the table

  sharing_ratio = backend / (backend + glue + ui)

what a deliverable maps to: its platform family (the first word of platform_id: windows, linux, macos,
ios, android, web) and its ui_variant give ui/<variant>/<platform>/ (windows legacy -> windows-win32,
linux legacy -> linux-xlib, linux modern -> linux-gtk3, ...) and the glue of the family. Several
records can share one UI (windows-2000-x86 and windows-11-x64 run the same sources).

What is counted (a decision, so the numbers are reproducible):
  * source files of the UI languages: C, C++ (.c .cc .cpp .cxx .h .hh .hpp .hxx), Objective-C (.m
    .mm), Java, Kotlin, Swift, C#, TypeScript, JavaScript, CSS (// and /* */ comments), HTML and
    XAML (<!-- --> comments). A line counts when it holds anything but white space once the
    comments are removed (a line of code with a trailing comment counts, a comment line does not).
  * NOT counted: tests (a directory named test or tests: core/tests), generated code (a file whose
    first lines say it is generated, or in a directory named generated), packaging and build files
    (CMakeLists.txt, *.cmake, *.gradle, *.rc version and string resources, *.manifest, *.plist,
    *.xml, *.json, linker maps and export lists, icons), third-party code, build output.
  * Python tools, specs and documentation are not application code and are never counted.

--write      store shared_loc (backend), glue_loc, ui_loc and sharing_ratio (0-1, 4 decimals) in every
             deliverable record (the other fields are left as they are). Without it nothing is written.
--format     text (default, a table) or json (the same numbers, for tools/report.py).
--verbose    text: also the line count of every counted file.
--min-ratio  the share below which a row is marked "BELOW" (default 0.8, SC-007): such a gap must
             be justified in the report (T107), it is not hidden here.
--platform   keep only the deliverable records of these platform ids (comma-separated) and the UIs they
             use: the evidence of one platform (the numbers do not change).
--strict     exit status 1 when a row is below --min-ratio (default 0: this is a measurement).
--selftest   check the tool on a temporary tree with known counts and exit.

Exit status: 0, 1 (--strict and a row below the minimum, or a failed self-test), 2 usage error.
Python 3.8+, standard library only.
"""
import argparse
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

import check_ui_logic
import common

C_FAMILY = {".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx", ".m", ".mm", ".java", ".kt",
            ".swift", ".cs", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".css"}
XML_FAMILY = {".html", ".htm", ".xaml"}
SKIP_DIRS = {"test", "tests", "generated", "build", "out", "node_modules", "pods", "deriveddata",
             "third_party", "__pycache__", ".git", ".gradle"}
GENERATED_MARKERS = ("@generated", "do not edit", "auto-generated", "autogenerated",
                     "automatically generated", "generated by", "this file is generated")
HEADER_LINES = 5

# (platform family, ui_variant) -> directory name of the UI under ui/<variant>/
UI_DIR = {
    ("windows", "legacy"): "windows-win32", ("windows", "modern"): "windows-winui3",
    ("linux", "legacy"): "linux-xlib", ("linux", "modern"): "linux-gtk3",
    ("macos", "legacy"): "macos-appkit", ("macos", "modern"): "macos-swiftui",
    ("ios", "legacy"): "ios-uikit", ("ios", "modern"): "ios-swiftui",
    ("android", "legacy"): "android-views", ("android", "modern"): "android-compose",
    ("web", "legacy"): "web-es5", ("web", "modern"): "web-ts",
}
# platform family -> bridge directory (glue between the C API and the UI language)
GLUE_DIR = {"android": "jni", "web": "wasm"}


def is_generated(text):
    head = "\n".join(text.splitlines()[:HEADER_LINES]).lower()
    return any(m in head for m in GENERATED_MARKERS)


def count_file(path):
    """Number of non-empty, non-comment lines of a source file; None when the file is not counted."""
    ext = path.suffix.lower()
    if ext in C_FAMILY:
        style = "c"
    elif ext in XML_FAMILY:
        style = "xml"
    else:
        return None
    text = path.read_bytes().decode("utf-8", errors="replace")
    if is_generated(text):
        return None
    code = check_ui_logic.blank_comments(text, style)
    return sum(1 for line in code.splitlines() if line.strip())


def count_tree(directory):
    """(lines, {relative path: lines}) of the counted files under `directory`."""
    directory = Path(directory)
    total, files = 0, {}
    if not directory.is_dir():
        return total, files
    for dirpath, dirnames, filenames in os.walk(str(directory)):
        dirnames[:] = sorted(d for d in dirnames if d.lower() not in SKIP_DIRS)
        for name in sorted(filenames):
            path = Path(dirpath) / name
            n = count_file(path)
            if n is not None:
                files[path.relative_to(directory).as_posix()] = n
                total += n
    return total, files


def ratio_of(backend, glue, ui):
    whole = backend + glue + ui
    return round(float(backend) / whole, 4) if whole else 0.0


def measure(root):
    """The measurement of a repository: backend, bridges, UIs and the rows of the deliverables."""
    root = Path(root)
    backend, backend_files = count_tree(root / "core")
    bridges = {}
    for d in sorted(p for p in (root / "bridge").iterdir() if p.is_dir()) if (root / "bridge").is_dir() else []:
        bridges[d.name] = count_tree(d)
    uis = {}
    for label, directory in check_ui_logic.ui_dirs(root / "ui"):
        n, files = count_tree(directory)
        uis[label] = (n, files)
    result = {"backend": {"lines": backend, "files": backend_files},
              "bridges": {k: {"lines": v[0], "files": v[1]} for k, v in bridges.items()},
              "uis": [], "deliverables": []}
    for label, (n, files) in sorted(uis.items()):
        variant, plat = label.split("/")
        glue = [g for (fam, var), d in UI_DIR.items() if d == plat and var == variant
                for g in [GLUE_DIR.get(fam)] if g]
        glue_lines = bridges[glue[0]][0] if glue and glue[0] in bridges else 0
        result["uis"].append({"ui": label, "variant": variant, "backend_loc": backend, "glue_loc": glue_lines,
                              "ui_loc": n, "sharing_ratio": ratio_of(backend, glue_lines, n), "files": files})
    deliverables = root / "docs" / "implementation" / "validation" / "deliverables"
    if deliverables.is_dir():
        for path in sorted(deliverables.glob("*.json")):
            rec = common.read_json(path)
            family, variant = rec["platform_id"].split("-")[0], rec["ui_variant"]
            plat = UI_DIR.get((family, variant))
            n = uis.get("%s/%s" % (variant, plat), (0, {}))[0]
            glue = bridges.get(GLUE_DIR.get(family, ""), (0, {}))[0]
            result["deliverables"].append({
                "record": path.name, "platform_id": rec["platform_id"], "ui_variant": variant,
                "ui": "%s/%s" % (variant, plat), "backend_loc": backend, "glue_loc": glue, "ui_loc": n,
                "sharing_ratio": ratio_of(backend, glue, n), "ui_has_code": n > 0})
    return result


def filter_platforms(result, ids):
    """The measurement restricted to the records of the platform ids and the UIs they use."""
    kept = [d for d in result["deliverables"] if d["platform_id"] in ids]
    used = set(d["ui"] for d in kept)
    out = dict(result)
    out["deliverables"] = kept
    out["uis"] = [u for u in result["uis"] if u["ui"] in used]
    return out


def rows_of(result):
    return [("deliverable " + d["platform_id"] + "-" + d["ui_variant"], d) for d in result["deliverables"] if d["ui_has_code"]] + \
           [("ui " + u["ui"], u) for u in result["uis"]]


def render_text(result, min_ratio, verbose):
    lines = ["Shared-code share: non-empty, non-comment lines; ratio = backend / (backend + glue + ui)",
             "backend core/            %6d lines in %d file(s)" % (result["backend"]["lines"], len(result["backend"]["files"]))]
    for name, b in sorted(result["bridges"].items()):
        lines.append("glue    bridge/%-10s %6d lines in %d file(s)" % (name, b["lines"], len(b["files"])))
    lines.append("")
    lines.append("%-52s %8s %6s %8s %8s" % ("platform / variant", "backend", "glue", "ui", "shared"))
    seen_below = []
    for title, row in rows_of(result):
        below = row["sharing_ratio"] < min_ratio
        if below:
            seen_below.append(title)
        lines.append("%-52s %8d %6d %8d %7.1f%%%s" % (title, row["backend_loc"], row["glue_loc"], row["ui_loc"],
                                                      row["sharing_ratio"] * 100, "  BELOW %d%%" % round(min_ratio * 100) if below else ""))
    for d in result["deliverables"]:
        if not d["ui_has_code"]:
            lines.append("%-52s no code in %s (not measured)" % ("deliverable " + d["platform_id"] + "-" + d["ui_variant"], d["ui"]))
    if verbose:
        lines.append("")
        for f, n in sorted(result["backend"]["files"].items()):
            lines.append("  core/%-60s %6d" % (f, n))
        for name, b in sorted(result["bridges"].items()):
            for f, n in sorted(b["files"].items()):
                lines.append("  bridge/%s/%-52s %6d" % (name, f, n))
        for u in result["uis"]:
            for f, n in sorted(u["files"].items()):
                lines.append("  ui/%s/%-55s %6d" % (u["ui"], f, n))
    lines.append("")
    lines.append("%d row(s) below %d%% (SC-007: each gap must be justified in the report)" % (len(seen_below), round(min_ratio * 100)))
    return "\n".join(lines), seen_below


def write_records(root, result):
    """Store the four fields in every deliverable record; returns the list of records written."""
    written = []
    deliverables = Path(root) / "docs" / "implementation" / "validation" / "deliverables"
    for d in result["deliverables"]:
        if not d["ui_has_code"]:
            continue
        path = deliverables / d["record"]
        rec = common.read_json(path)
        rec["shared_loc"], rec["glue_loc"], rec["ui_loc"] = d["backend_loc"], d["glue_loc"], d["ui_loc"]
        rec["sharing_ratio"] = d["sharing_ratio"]
        common.write_json(path, rec)
        written.append(d["record"])
    return written


# ---- self-test ---------------------------------------------------------------------------------

def selftest():
    base = Path(tempfile.mkdtemp(prefix="loomora-sharing-"))
    failures = []

    def put(rel, text):
        p = base / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")

    def expect(name, got, want):
        ok = got == want
        print("%s selftest %-58s got %r, want %r" % ("OK  " if ok else "FAIL", name, got, want))
        if not ok:
            failures.append(name)

    try:
        put("core/src/a.cpp", "// comment\n\nint a;   // trailing\n/* block\n   still */\nint b;\nconst char* s = \"// not a comment\";\n")  # 3 lines
        put("core/include/a.h", "#pragma once\nint f();\n")                                     # 2
        put("core/src/gen.cpp", "// generated by a tool, do not edit\nint g1;\nint g2;\n")      # generated: not counted
        put("core/tests/t.cpp", "int test1;\nint test2;\n")                                      # tests: not counted
        put("core/CMakeLists.txt", "add_library(x a.cpp)\n")                                     # build file: not counted
        put("bridge/jni/j.cpp", "int j1;\nint j2;\n")                                            # 2
        put("ui/modern/linux-gtk3/m.cpp", "int u;\n" * 5 + "// c\n")                             # 5
        put("ui/modern/linux-gtk3/app.rc", "1 VERSIONINFO\n")                                    # packaging: not counted
        put("ui/legacy/android-views/A.java", "class A {\n}\n")                                  # 2
        put("docs/implementation/validation/deliverables/linux-x-1-modern.json",
            json.dumps({"platform_id": "linux-x-1", "ui_variant": "modern", "notes": "n"}))
        put("docs/implementation/validation/deliverables/android-api-10-legacy.json",
            json.dumps({"platform_id": "android-api-10", "ui_variant": "legacy"}))
        put("docs/implementation/validation/deliverables/web-chrome-modern.json",
            json.dumps({"platform_id": "web-chrome", "ui_variant": "modern"}))
        r = measure(base)
        expect("backend lines (comments, blanks, tests, generated, build)", r["backend"]["lines"], 5)
        expect("bridge lines", r["bridges"]["jni"]["lines"], 2)
        byui = dict((u["ui"], u) for u in r["uis"])
        expect("gtk ui lines (resources not counted)", byui["modern/linux-gtk3"]["ui_loc"], 5)
        expect("gtk ratio 5/(5+0+5)", byui["modern/linux-gtk3"]["sharing_ratio"], 0.5)
        expect("android ratio 5/(5+2+2)", byui["legacy/android-views"]["sharing_ratio"], round(5 / 9.0, 4))
        recs = dict((d["record"], d) for d in r["deliverables"])
        expect("linux record maps to its UI", recs["linux-x-1-modern.json"]["ui"], "modern/linux-gtk3")
        expect("android record gets the JNI glue", recs["android-api-10-legacy.json"]["glue_loc"], 2)
        expect("record without UI code is not measured", recs["web-chrome-modern.json"]["ui_has_code"], False)
        written = write_records(base, r)
        expect("records written", written, ["android-api-10-legacy.json", "linux-x-1-modern.json"])
        rec = common.read_json(base / "docs/implementation/validation/deliverables/linux-x-1-modern.json")
        expect("record fields", [rec[k] for k in ("shared_loc", "glue_loc", "ui_loc", "sharing_ratio", "notes")], [5, 0, 5, 0.5, "n"])
        rec = common.read_json(base / "docs/implementation/validation/deliverables/web-chrome-modern.json")
        expect("unmeasured record left alone", "sharing_ratio" in rec, False)
        f = filter_platforms(r, {"linux-x-1"})
        expect("platform filter keeps its record and UI", ([d["record"] for d in f["deliverables"]], [u["ui"] for u in f["uis"]]), (["linux-x-1-modern.json"], ["modern/linux-gtk3"]))
        text, below = render_text(r, 0.8, False)
        expect("rows below 80% (2 records + 2 UIs)", len(below), 4)
        expect("text table has the percentage", "50.0%" in text, True)
    finally:
        shutil.rmtree(str(base), ignore_errors=True)
    print("selftest: %d failed" % len(failures))
    return 1 if failures else 0


def main(argv=None):
    common.setup_utf8_output()
    ap = argparse.ArgumentParser(description="Measure the shared-code share per platform and variant.")
    ap.add_argument("--root", default=str(common.ROOT), help="repository root (default: this repository)")
    ap.add_argument("--format", choices=("text", "json"), default="text")
    ap.add_argument("--verbose", action="store_true", help="text: the line count of every counted file")
    ap.add_argument("--write", action="store_true", help="store the numbers in the deliverable records")
    ap.add_argument("--platform", help="comma-separated platform ids: keep their records and UIs only")
    ap.add_argument("--min-ratio", type=float, default=0.8, help="share below which a row is marked (default 0.8)")
    ap.add_argument("--strict", action="store_true", help="exit 1 when a row is below --min-ratio")
    ap.add_argument("--selftest", action="store_true", help="check the tool on a temporary tree and exit")
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    if not Path(args.root).is_dir() or not (Path(args.root) / "core").is_dir():
        print("measure_sharing: %s has no core/ directory" % args.root, file=sys.stderr)
        return 2
    result = measure(args.root)
    if args.platform:
        result = filter_platforms(result, set(args.platform.split(",")))
    text, below = render_text(result, args.min_ratio, args.verbose)
    if args.format == "json":
        slim = dict(result)
        slim["min_ratio"], slim["below_min_ratio"] = args.min_ratio, below
        print(json.dumps(slim, ensure_ascii=False, indent=2, sort_keys=True))
    else:
        print(text)
    if args.write:
        if not common.docs_present():
            print("measure_sharing: --write needs docs/implementation: %s" % common.docs_missing_message("nothing written"), file=sys.stderr)
            return 2
        written = write_records(args.root, result)
        print("records updated: %s" % (", ".join(written) if written else "none"), file=sys.stderr if args.format == "json" else sys.stdout)
    return 1 if (args.strict and below) else 0


if __name__ == "__main__":
    sys.exit(main())
