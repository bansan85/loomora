Bytes bytes_of(const unsigned char *p, std::size_t n) { return Bytes(p, p + n); }

std::string issue_code_of(const Bytes &data, bool sequence) {
    try {
        MemorySource src(&data[0], data.size());
        if (sequence) {
            std::vector<SequenceStep> out;
            decode_sequence(src, &out);
        } else {
            MeshData mesh;
            read_mesh(src, &mesh);
        }
    } catch (const FormatError &e) {
        return e.has_issue() ? e.issue().code : std::string("(no code)");
    }
    return std::string();
}

// By hand, without endian.hpp.
std::uint32_t le32(const unsigned char *p) {
    return static_cast<std::uint32_t>(p[0]) + static_cast<std::uint32_t>(p[1]) * 256u +
           static_cast<std::uint32_t>(p[2]) * 65536u + static_cast<std::uint32_t>(p[3]) * 16777216u;
}
unsigned le16(const unsigned char *p) { return static_cast<unsigned>(p[0]) + static_cast<unsigned>(p[1]) * 256u; }

